#!/bin/sh
set -eu

: "${RELEASEFOUNDRY_WORKER_HEARTBEAT_PATH:?RELEASEFOUNDRY_WORKER_HEARTBEAT_PATH is required}"
: "${RELEASEFOUNDRY_WORKER_READINESS_PATH:?RELEASEFOUNDRY_WORKER_READINESS_PATH is required}"
: "${RELEASEFOUNDRY_WORKER_LANE:?RELEASEFOUNDRY_WORKER_LANE is required}"
: "${RELEASEFOUNDRY_WORKER_QUEUE:?RELEASEFOUNDRY_WORKER_QUEUE is required}"
: "${RELEASEFOUNDRY_PAYMENT_WORKER_PROVIDER_FAMILY:?RELEASEFOUNDRY_PAYMENT_WORKER_PROVIDER_FAMILY is required}"

test -s "$RELEASEFOUNDRY_WORKER_READINESS_PATH"
test -s "$RELEASEFOUNDRY_WORKER_HEARTBEAT_PATH"
find "$RELEASEFOUNDRY_WORKER_HEARTBEAT_PATH" -mmin -2 -type f | grep -q .
grep -Eq '"status":"(ready|disabled)"' "$RELEASEFOUNDRY_WORKER_READINESS_PATH"
grep -q "\"lane\":\"$RELEASEFOUNDRY_WORKER_LANE\"" "$RELEASEFOUNDRY_WORKER_READINESS_PATH"
grep -q "\"provider_family\":\"$RELEASEFOUNDRY_PAYMENT_WORKER_PROVIDER_FAMILY\"" "$RELEASEFOUNDRY_WORKER_READINESS_PATH"
grep -q "\"queue\":\"$RELEASEFOUNDRY_WORKER_QUEUE\"" "$RELEASEFOUNDRY_WORKER_READINESS_PATH"
grep -q '"provider_network_enabled":false' "$RELEASEFOUNDRY_WORKER_READINESS_PATH"
